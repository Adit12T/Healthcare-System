-- Runs on H2 and PostgreSQL.
CREATE TABLE staff_member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40)  NOT NULL UNIQUE,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    department    VARCHAR(60),
    password_hash VARCHAR(100) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE patient (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        VARCHAR(60)  NOT NULL,
    last_name         VARCHAR(60)  NOT NULL,
    date_of_birth     DATE         NOT NULL,
    sex               VARCHAR(10)  NOT NULL,
    blood_group       VARCHAR(12),
    phone             VARCHAR(20)  NOT NULL,
    address           VARCHAR(200),
    emergency_contact VARCHAR(120),
    created_at        TIMESTAMP    NOT NULL
);
CREATE INDEX ix_patient_name ON patient (last_name, first_name);

CREATE TABLE room (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(10)  NOT NULL UNIQUE,
    floor      INT           NOT NULL,
    room_type  VARCHAR(20)   NOT NULL,
    daily_rate NUMERIC(10,2) NOT NULL CHECK (daily_rate >= 0)
);

CREATE TABLE bed (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT      NOT NULL REFERENCES room (id),
    label   VARCHAR(10) NOT NULL,
    CONSTRAINT uq_bed UNIQUE (room_id, label)
);

CREATE TABLE admission (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id        BIGINT       NOT NULL REFERENCES patient (id),
    bed_id            BIGINT       NOT NULL REFERENCES bed (id),
    reason            VARCHAR(300) NOT NULL,
    attending_doctor  VARCHAR(100),
    admitted_at       TIMESTAMP    NOT NULL,
    discharged_at     TIMESTAMP,
    discharge_summary VARCHAR(2000),
    stay_charge       NUMERIC(10,2)
);
CREATE INDEX ix_admission_open ON admission (bed_id, discharged_at);

CREATE TABLE donor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    date_of_birth DATE         NOT NULL,
    blood_group   VARCHAR(12)  NOT NULL,
    weight_kg     INT          NOT NULL,
    phone         VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE donation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id    BIGINT      NOT NULL REFERENCES donor (id),
    blood_group VARCHAR(12) NOT NULL,
    units       INT         NOT NULL CHECK (units BETWEEN 1 AND 2),
    donated_on  DATE        NOT NULL
);

CREATE TABLE blood_issue (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT      NOT NULL REFERENCES patient (id),
    blood_group VARCHAR(12) NOT NULL,
    units       INT         NOT NULL CHECK (units > 0),
    issued_on   DATE        NOT NULL,
    issued_by   VARCHAR(40) NOT NULL
);

CREATE TABLE ambulance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration VARCHAR(20) NOT NULL UNIQUE,
    kind         VARCHAR(20) NOT NULL,
    status       VARCHAR(20) NOT NULL
);

CREATE TABLE dispatch (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ambulance_id   BIGINT       NOT NULL REFERENCES ambulance (id),
    patient_name   VARCHAR(100) NOT NULL,
    pickup_address VARCHAR(200) NOT NULL,
    contact_phone  VARCHAR(20)  NOT NULL,
    dispatched_at  TIMESTAMP    NOT NULL,
    returned_at    TIMESTAMP
);
